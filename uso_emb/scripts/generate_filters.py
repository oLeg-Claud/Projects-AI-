"""Regenerate committed SOS coefficients: pip install scipy."""
from pathlib import Path
from scipy.signal import butter

CUTOFFS = [20, 15, 12, 9, 6.5, 4.3, 3, 11, 8, 6, 4, 3, 2.5, 2]
def generate():
    lines = ["/* Generated by scripts/generate_filters.py; Butterworth order 10, Fs=400 Hz.",
             " * Each section: b0,b1,b2,a1,a2 (a0=1). */",
             "static const double filter_sos[14][5][5] = {"]
    for cutoff in CUTOFFS:
        sos = butter(10, cutoff, fs=400, output="sos")
        # Spread the very small total gain equally over all sections.
        gain = sos[0, 0] ** (1 / 5)
        sos[:, :3] = [gain, 2 * gain, gain]
        lines.append(f"    {{ /* {cutoff:g} Hz */")
        for row in sos:
            lines.append("        {" + ", ".join(f"{v:.17g}" for v in [*row[:3], *row[4:]]) + "},")
        lines.append("    },")
    lines.append("};\n")
    return "\n".join(lines)

if __name__ == "__main__":
    (Path(__file__).resolve().parents[1] / "src/filter_coeffs.inc").write_text(generate(), encoding="utf-8")
